def aumentar(num):
    dez_porcento_up = num + (num * 0.10)
    return dez_porcento_up
def diminuir(num):
    treze_porcento_down = num - (num * 0.13)
    return treze_porcento_down

def dobro(num):
    dobrando = num * 2
    return dobrando

def metade(num):
    divisao = num / 2
    return divisao